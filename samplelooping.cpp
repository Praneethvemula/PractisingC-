#include<iostream>
using namespace std;
 int main(){

    // Declare an integer variable i and initialize it to 1
    int i = 1;

    // Use a while loop to print numbers from 1 to 10
    while(i<=10){

        // Print the current value of i
        cout<<i<<endl;

        // Increase i by 1 (i = i + 1)
        i++;
    }
    return 0;
 }