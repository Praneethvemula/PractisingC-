#include<iostream>
using namespace std;
int main(){
    int i, j,add,sub,mul,div,rem;

    i = 13;
    j = 5;
    add=i+j;
    sub=i-j;
    mul=i*j;
    div=i/j;
    rem= i % j;
    
    cout<<"addition:"<<add<<endl;
    cout<<"subtraction:"<<sub<<endl;
    cout<<"multiplication:"<<mul<<endl;
    cout<<"division:"<<div<<endl;
    cout<<"remainder:"<<rem<<endl;
    
}