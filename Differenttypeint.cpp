    cout<<"The size of long int is:"<<sizeof(long int)<<"bytes"<<endl;

    // Display the size of short int in bytes
    cout<<"The size of short int is:"<<sizeof(short int)<<"bytes"<<endl;

    // Display the size of signed int in bytes
    cout<<"the size of signed int:"<<sizeof(signed int)<<"bytes"<<endl;

    // Display the size of unsigned int in bytes
    cout<<"The size of unsigned int is:"<<sizeof(unsigned int)<<"bytes"<<endl;

    // Display the size of long long int in bytes
    cout<<"The size of the long long int is:"<<sizeof(long long int)<<"bytes"<<endl;
    
